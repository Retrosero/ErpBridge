namespace Fora.Mikro.Utility;

public class HardDrive
{
	private string model;

	private string type;

	private string serialNo;

	public string Model
	{
		get
		{
			return model;
		}
		set
		{
			model = value;
		}
	}

	public string Type
	{
		get
		{
			return type;
		}
		set
		{
			type = value;
		}
	}

	public string SerialNo
	{
		get
		{
			return serialNo;
		}
		set
		{
			serialNo = value;
		}
	}
}
